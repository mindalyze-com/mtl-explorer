def release_page(release, repository, releases):
    body, chapters = render_markdown(release.content, release, repository, releases)
    toc = ""
    if chapters:
        links = "".join(f'<li><a href="#{identifier}">{escape(title)}</a></li>' for title, identifier in chapters)
        toc = f'    <details class="release-contents"><summary>On this page</summary><ul>{links}</ul></details>'
    github_link = (f'<a class="button-secondary" href="{GITHUB}/releases/tag/{release.tag}">View on GitHub</a>'
                   if release.released_on else "")
    content = f'''    <header class="release-header">
      <h1>{escape(release.title)}</h1>
      <p class="release-meta">{publication_label(release)}</p>
    </header>
{toc}
    <article class="article-copy release-content">{body}</article>
    <div class="actions"><a class="button-secondary" href="/releases/">All releases</a>{github_link}</div>'''
    return document(f"MTL Explorer {release.number} release notes", release.teaser, release.url,
                    content, [("Home", "/"), ("Releases", "/releases/"), (release.number, release.url)])


def archive(releases, repository):
    sections = []
    for title, filtered in [("Upcoming", [r for r in releases if r.released_on is None]),
                            ("Published releases", [r for r in releases if r.released_on])]:
        if filtered:
            rows = "\n".join(release_row(release, repository, releases) for release in filtered)
            sections.append(f'<section class="release-archive-section"><h2>{title}</h2><div class="release-list">{rows}</div></section>')
    content = '''    <header class="release-header">
      <h1>Release notes</h1>
      <p class="lead">Features, improvements, and fixes in each MTL Explorer release.</p>
    </header>
    ''' + "\n    ".join(sections)
    return document("MTL Explorer release history", "Browse MTL Explorer releases, upcoming changes, and upgrade notes.",
                    "/releases/", content, [("Home", "/"), ("Releases", "/releases/")])


def replace_region(text, start, end, content):
    if text.count(start) != 1 or text.count(end) != 1:
        raise ValueError(f"Expected exactly one {start} / {end} region")
    before, rest = text.split(start, 1)
    _, after = rest.split(end, 1)
    return before + start + "\n" + content + "\n" + end + after


def generate(repository=REPOSITORY, check=False):
    repository = repository.resolve()
    root = repository / "docs"
    releases = load_releases(repository / "documentation/release-notes")
    outputs = {root / "releases/index.html": archive(releases, repository)}
    feed_path = root / "releases/releases.json"
    outputs[feed_path] = json.dumps(release_feed(repository, releases, ORIGIN), indent=2) + "\n"
    for release in releases:
        outputs[root / release.url.lstrip("/") / "index.html"] = release_page(release, repository, releases)
    homepage = replace_region((root / "index.html").read_text(encoding="utf-8"),
                              NEWS_START, NEWS_END, news(releases, repository))
    outputs[root / "index.html"] = replace_region(homepage, ANNOUNCEMENT_START, ANNOUNCEMENT_END,
                                                   announcement(releases))
    urls = ["/releases/"] + [release.url for release in releases]
    entries = "\n".join(f"  <url><loc>{ORIGIN}{url}</loc></url>" for url in urls)
    outputs[root / "sitemap.xml"] = replace_region((root / "sitemap.xml").read_text(encoding="utf-8"),
                                                    SITEMAP_START, SITEMAP_END, entries)
    stale = [path for path in (root / "releases").rglob("index.html")
             if path not in outputs and GENERATED in path.read_text(encoding="utf-8")]
    changed = [path for path, content in outputs.items()
               if not path.exists() or path.read_text(encoding="utf-8") != content]
    if check:
        for path in changed + stale:
            print(f"Out of date: {path.relative_to(repository)}")
        if changed or stale:
            return 1
        print(f"Release generation: PASS ({len(releases)} releases)")
        return 0
    for path in changed:
        if path != feed_path and path.parent.name != "docs" and path.exists() and GENERATED not in path.read_text(encoding="utf-8"):
            raise ValueError(f"Refusing to overwrite a manually maintained page: {path}")
    for path in changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(outputs[path], encoding="utf-8")
    for path in stale:
        path.unlink()
        if not any(path.parent.iterdir()):
            path.parent.rmdir()
    print(f"Generated {len(releases)} releases; updated {len(changed)} files; removed {len(stale)} stale pages.")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check generated output without writing")
    args = parser.parse_args()
    try:
        return generate(check=args.check)
    except ValueError as error:
        print(f"Release generation failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
