"""Render public documentation and the installed guide from Markdown sources."""

import argparse
from dataclasses import dataclass
from html import escape
import hashlib
import json
from pathlib import Path
import re
import struct
from urllib.parse import quote, unquote, urlsplit, urlunsplit

from markdown_it import MarkdownIt

if __package__:
    from .release_notes import load_release_note
else:
    from release_notes import load_release_note

REPOSITORY = Path(__file__).resolve().parents[3]
ORIGIN = "https://mtl-explorer.com"
GITHUB = "https://github.com/mindalyze-com/mtl-explorer"
AREAS = ("user", "administration", "development", "architecture", "project", "legal", "versions")
INSTALLED_AREAS = ("user", "administration")
SITE_BASE = "/docs/"
INSTALLED_BASE = "/mtl/guide/"
CURRENT_GUIDE_VERSION = "0.9.0"
GENERATED = "<!-- Generated by documentation/tools/website/generate_documentation.py; edit Markdown sources. -->"
SITEMAP_START = "<!-- DOCUMENTATION URLS START -->"
SITEMAP_END = "<!-- DOCUMENTATION URLS END -->"
MARKDOWN = MarkdownIt("commonmark", {"html": False}).enable("table")


@dataclass
class Document:
    path: Path
    title: str
    text: str
    url: str
    scope: str


def plain(text):
    tokens = MARKDOWN.parseInline(text)
    return " ".join("".join(
        child.content if child.type in {"text", "code_inline", "image"} else " "
        for child in tokens[0].children or []
    ).split())


def slug(title):
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-") or "section"


def page_url(relative, installed=False):
    if installed:
        if relative.parts[0] == "user":
            relative = Path(*relative.parts[1:])
        base = INSTALLED_BASE
    else:
        base = SITE_BASE
    parts = relative.with_suffix("").parts
    if parts[-1] == "README":
        parts = parts[:-1]
    suffix = "/".join(quote(part.lower()) for part in parts)
    if suffix:
        suffix += "/"
    return base + suffix + ("index.html" if installed else "")


def load_documents(repository, installed=False):
    root = repository / "documentation"
    areas = INSTALLED_AREAS if installed else AREAS
    paths = {path for area in areas for path in (root / area).rglob("*.md")}
    if not installed:
        paths.update({root / "README.md", root / "features.md"})
    documents = {}
    note_path = root / "release-notes" / f"v.{CURRENT_GUIDE_VERSION}.md"
    published = note_path.is_file() and load_release_note(note_path).released_on is not None
    current_scope = f"Released · {CURRENT_GUIDE_VERSION}" if published else f"Development · upcoming {CURRENT_GUIDE_VERSION}"
    for path in sorted(paths):
        if not path.is_file():
            raise ValueError(f"Missing documentation source: {path}")
        text = path.read_text()
        headings = [token for token in MARKDOWN.parse(text) if token.type == "heading_open" and token.tag == "h1"]
        match = re.search(r"^# (.+)$", text, re.M)
        if len(headings) != 1 or not match:
            raise ValueError(f"{path}: use one H1 title")
        relative = path.relative_to(root)
        scope = "Guide included with this build" if installed else current_scope
        if relative.parts[0] == "versions":
            scope = "Released guides" if len(relative.parts) == 2 else f"Released · {relative.parts[1]}"
        if relative == Path("README.md"):
            scope = "Released and development documentation"
        documents[path.resolve()] = Document(path, plain(match[1]), text, page_url(relative, installed), scope)
    urls = [doc.url for doc in documents.values()]
    if len(set(urls)) != len(urls):
        raise ValueError("Documentation URLs are not unique")
    return documents


def image_size(path):
    data = path.read_bytes()
    if data.startswith(b"\x89PNG\r\n\x1a\n"):
        return struct.unpack(">II", data[16:24])
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        chunk = data[12:16]
        if chunk == b"VP8X":
            return int.from_bytes(data[24:27], "little") + 1, int.from_bytes(data[27:30], "little") + 1
        if chunk == b"VP8 ":
            return tuple(value & 0x3FFF for value in struct.unpack("<HH", data[26:30]))
        if chunk == b"VP8L":
            bits = int.from_bytes(data[21:25], "little")
            return (bits & 0x3FFF) + 1, ((bits >> 14) & 0x3FFF) + 1
    raise ValueError(f"Unsupported documentation image: {path}")


def rewrite_reference(href, document, documents, repository, installed, images):
    value = urlsplit(href)
    if value.scheme or value.netloc or not value.path:
        return href
    target = (document.path.parent / unquote(value.path)).resolve()
    if not target.is_relative_to(repository.resolve()):
        raise ValueError(f"{document.path}: reference escapes repository: {href}")
    if target.is_relative_to(repository / "docs-my"):
        raise ValueError(f"{document.path}: public reference to internal material: {href}")
    if not target.exists():
        raise ValueError(f"{document.path}: missing reference: {href}")
    fragment = value.fragment
    if target in documents:
        url = documents[target].url
    elif target == repository / "documentation/release-notes/README.md":
        url = f"{ORIGIN if installed else ''}/releases/"
    elif target.suffix == ".md" and target.is_relative_to(repository / "documentation/release-notes") and re.fullmatch(r"v\.\d+\.\d+\.\d+", target.stem):
        url = f"{ORIGIN if installed else ''}/releases/{target.stem[2:]}/"
    elif target.is_relative_to(repository / "docs"):
        if installed and target.suffix.lower() in {".webp", ".png"}:
            filename = hashlib.sha256(target.read_bytes()).hexdigest()[:12] + target.suffix
            images[filename] = target
            url = INSTALLED_BASE + "assets/" + filename
        else:
            url = (ORIGIN if installed else "") + "/" + quote(target.relative_to(repository / "docs").as_posix())
    elif installed and target.is_relative_to(repository / "documentation") and target.parts[len(repository.parts) + 1] in AREAS:
        url = ORIGIN + page_url(target.relative_to(repository / "documentation"))
    else:
        kind = "tree" if target.is_dir() else "blob"
        url = f"{GITHUB}/{kind}/main/{quote(target.relative_to(repository).as_posix())}"
    return urlunsplit((*urlsplit(url)[:3], value.query, fragment))


def render_body(document, documents, repository, installed, images):
    tokens = MARKDOWN.parse(document.text)
    contents, counts = [], {}
    for index, token in enumerate(tokens):
        if token.type == "heading_open":
            name = plain(tokens[index + 1].content)
            key = slug(name)
            counts[key] = counts.get(key, 0) + 1
            identifier = key if counts[key] == 1 else f"{key}-{counts[key]}"
            token.attrSet("id", identifier)
            if token.tag == "h2":
                contents.append((name, identifier))
        for child in token.children or []:
            for attribute in ("href", "src"):
                href = child.attrGet(attribute)
                if href:
                    child.attrSet(attribute, rewrite_reference(href, document, documents, repository, installed, images))
            if child.type == "image":
                original = urlsplit(child.attrGet("src") or "")
                if original.path.startswith(INSTALLED_BASE + "assets/"):
                    target = images[Path(original.path).name]
                elif original.path.startswith("/") and not original.netloc:
                    target = repository / "docs" / unquote(original.path).lstrip("/")
                else:
                    raise ValueError(f"{document.path}: use a local documentation image")
                width, height = image_size(target)
                child.attrSet("width", str(width))
                child.attrSet("height", str(height))
                child.attrSet("loading", "lazy")
    return MARKDOWN.renderer.render(tokens, MARKDOWN.options, {}), contents


def ordered_children(index, documents):
    result = []
    parent = index.path.parent.resolve()
    for token in MARKDOWN.parse(index.text):
        for child in token.children or []:
            if child.type != "link_open":
                continue
            value = urlsplit(child.attrGet("href") or "")
            if value.scheme or value.netloc or not value.path:
                continue
            target = (parent / unquote(value.path)).resolve()
            if target in documents and target != index.path.resolve() and target.parent.is_relative_to(parent) and target not in result:
                result.append(target)
    return result


def navigation(documents, repository, installed, current):
    root = repository / "documentation"
    sections = INSTALLED_AREAS if installed else ("versions", *(area for area in AREAS if area != "versions"))
    rows = []

    def link(document):
        attribute = ' aria-current="page"' if document.url == current else ""
        return f'<a href="{escape(document.url)}"{attribute}>{escape(document.title)}</a>'

    for section in sections:
        index_path = (root / section / "README.md").resolve()
        if index_path not in documents:
            continue
        index = documents[index_path]
        children = ordered_children(index, documents)
        links = []
        for path in children:
            child = documents[path]
            nested = ordered_children(child, documents) if path.name == "README.md" else []
            if nested:
                entries = "".join(f'<li>{link(documents[item])}</li>' for item in nested)
                links.append(f'<li><details{ " open" if current.startswith(child.url.removesuffix("index.html")) else ""}><summary>{link(child)}</summary><ul>{entries}</ul></details></li>')
            else:
                links.append(f"<li>{link(child)}</li>")
        active_section = any(doc.url == current and doc.path.is_relative_to(root / section) for doc in documents.values())
        rows.append(f'<details{ " open" if active_section else ""}><summary>{link(index)}</summary><ul>{"".join(links)}</ul></details>')
    return "".join(rows)


def breadcrumbs(document, documents, repository, installed):
    root = repository / "documentation"
    home = documents[(root / ("user/README.md" if installed else "README.md")).resolve()]
    items = [("User guide" if installed else "Documentation", home.url)]
    for parent in reversed(document.path.relative_to(root).parents[:-1]):
        path = (root / parent / "README.md").resolve()
        if path in documents and documents[path].url not in {url for _, url in items}:
            items.append((documents[path].title, documents[path].url))
    if document.url not in {url for _, url in items}:
        items.append((document.title, document.url))
    if not installed:
        items.insert(0, ("Home", "/"))
    return items


def render_page(document, documents, repository, installed, images):
    body, contents = render_body(document, documents, repository, installed, images)
    crumbs = breadcrumbs(document, documents, repository, installed)
    base = INSTALLED_BASE if installed else SITE_BASE
    links = "".join(
        f'<li><span aria-current="page">{escape(title)}</span></li>' if url == document.url
        else f'<li><a href="{escape(url)}">{escape(title)}</a></li>'
        for title, url in crumbs
    )
    toc = "".join(f'<li><a href="#{identifier}">{escape(title)}</a></li>' for title, identifier in contents)
    description = f"{document.title}. {document.scope}. MTL Explorer {document.path.relative_to(repository / 'documentation').parent.as_posix().replace('/', ' ')} documentation."
    title = f"{document.title} | {document.scope} | MTL Explorer"
    if contents:
        contents_html = '<details class="doc-contents" open><summary>On this page</summary><nav aria-label="On this page"><ul>' + toc + '</ul></nav></details>'
        body = re.sub(r"<h2\b", lambda _: contents_html + "<h2", body, count=1)
    metadata = ""
    if not installed:
        canonical = ORIGIN + document.url
        schema = {"@context": "https://schema.org", "@type": "BreadcrumbList", "itemListElement": [
            {"@type": "ListItem", "position": i + 1, "name": name, "item": ORIGIN + url}
            for i, (name, url) in enumerate(crumbs)
        ]}
        metadata = f'<link rel="canonical" href="{canonical}"><meta property="og:url" content="{canonical}"><script type="application/ld+json">{json.dumps(schema)}</script>'
    else:
        metadata = '<meta name="robots" content="noindex">'
    theme = INSTALLED_BASE + "site-theme.css" if installed else "/site-theme.css"
    theme_script = f'<script src="{INSTALLED_BASE}guide-theme.js"></script>' if installed else ""
    navigation_script = f'<script defer src="{INSTALLED_BASE}guide-navigation.js"></script>' if installed else ""
    analytics_script = f'<script defer src="{INSTALLED_BASE}guide-analytics.js"></script>' if installed else '<script defer src="/site-analytics.js"></script>'
    back_attribute = ' data-guide-back' if installed else ""
    footer = "" if installed else f'<footer><a href="{GITHUB}/blob/main/{quote(document.path.relative_to(repository).as_posix())}">View source</a> · <a href="/#site-analytics">Site analytics</a></footer>'
    article_class = ' class="doc-overview"' if document.path == repository / "documentation/user/README.md" else ""
    menu_title = "Browse guide" if installed else "Browse documentation"
    return f'''<!doctype html>
{GENERATED}
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>{escape(title)}</title><meta name="description" content="{escape(description)}">{metadata}
{theme_script}<link rel="stylesheet" href="{theme}"><link rel="stylesheet" href="{base}documentation.css"><script defer src="{base}documentation.js"></script>{navigation_script}{analytics_script}</head>
<body><a class="skip-link" href="#content">Skip to content</a>
<header class="doc-header"><a class="doc-brand" href="{base}{'index.html' if installed else ''}">MTL Explorer</a><span>{escape(document.scope)}</span><a href="{'/mtl/' if installed else '/'}"{back_attribute}>{'Back to app' if installed else 'Home'}</a></header>
<div class="doc-layout"><aside><details id="doc-menu" open><summary>{menu_title}</summary>
<form role="search" class="doc-search"><label for="doc-query">Search documentation</label><input id="doc-query" type="search" placeholder="Search the guide…" autocomplete="off" data-index="{base}search-index.json"><div id="doc-results" hidden aria-live="polite"></div></form>
<nav class="doc-navigation" aria-label="Documentation">{navigation(documents, repository, installed, document.url)}</nav></details></aside>
<main id="content" tabindex="-1"><nav class="doc-breadcrumbs" aria-label="Breadcrumb"><ol>{links}</ol></nav>
<article{article_class}>{body}</article>{footer}</main></div></body></html>
'''


def sitemap(text, urls):
    block = SITEMAP_START + "\n" + "\n".join(f"  <url><loc>{ORIGIN}{url}</loc></url>" for url in sorted(urls)) + "\n" + SITEMAP_END
    if SITEMAP_START in text:
        return re.sub(re.escape(SITEMAP_START) + r".*?" + re.escape(SITEMAP_END), lambda _: block, text, flags=re.S)
    return text.replace("</urlset>", "  " + block + "\n</urlset>")


def generate(repository=REPOSITORY, check=False):
    repository = repository.resolve()
    outputs = {}
    for installed in (False, True):
        documents = load_documents(repository, installed)
        root = repository / ("mtl-client/public/guide" if installed else "docs/docs")
        base = INSTALLED_BASE if installed else SITE_BASE
        images = {}
        for document in documents.values():
            relative = document.url.removeprefix(base)
            if not installed:
                relative += "index.html"
            outputs[root / relative] = render_page(document, documents, repository, installed, images).encode()
        search = [{"title": doc.title, "url": doc.url, "scope": doc.scope, "text": plain(re.sub(r"```.*?```", "", doc.text, flags=re.S))} for doc in documents.values()]
        outputs[root / "search-index.json"] = (json.dumps(search, ensure_ascii=False, indent=2) + "\n").encode()
        for name in ("documentation.css", "documentation.js"):
            outputs[root / name] = (repository / "documentation/tools/website" / name).read_bytes()
        if installed:
            outputs[root / "guide-theme.js"] = (repository / "documentation/tools/website/guide-theme.js").read_bytes()
            outputs[root / "guide-navigation.js"] = (repository / "documentation/tools/website/guide-navigation.js").read_bytes()
            outputs[root / "guide-analytics.js"] = (repository / "documentation/tools/website/guide-analytics.js").read_bytes()
            outputs[root / "site-theme.css"] = (repository / "docs/site-theme.css").read_bytes()
            for name, image in images.items():
                outputs[root / "assets" / name] = image.read_bytes()
        else:
            path = repository / "docs/sitemap.xml"
            outputs[path] = sitemap(path.read_text(), [doc.url for doc in documents.values()]).encode()
    stale = [str(path.relative_to(repository)) for path, value in outputs.items() if not path.exists() or path.read_bytes() != value]
    for folder in (repository / "docs/docs", repository / "mtl-client/public/guide"):
        extra = [path for path in folder.rglob("*") if path.is_file() and path not in outputs]
        stale.extend(str(path.relative_to(repository)) for path in extra)
        if not check:
            for path in extra:
                path.unlink()
            for directory in sorted((path for path in folder.rglob("*") if path.is_dir()), key=lambda path: len(path.parts), reverse=True):
                if not any(directory.iterdir()):
                    directory.rmdir()
    if check:
        if stale:
            raise ValueError("Stale documentation output:\n" + "\n".join(stale))
    else:
        for path, value in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(value)
    return len(outputs)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check output without writing")
    parser.add_argument("--repository", type=Path, default=REPOSITORY)
    args = parser.parse_args()
    try:
        count = generate(args.repository, args.check)
    except (ValueError, OSError) as error:
        parser.exit(1, f"Documentation generation failed: {error}\n")
    print(f"{'Checked' if args.check else 'Generated'} {count} documentation files")


if __name__ == "__main__":
    main()
