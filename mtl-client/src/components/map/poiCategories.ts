export type PoiCategorySettings = Record<string, boolean>;
export const DEFAULT_POI_ENABLED = true;
export const DEFAULT_POI_OPACITY = 100;

export function defaultPoiCategories(): PoiCategorySettings {
  return Object.fromEntries(POI_CATEGORIES.map(({ id }) => [id, true]));
}

export function sanitizePoiCategories(value: unknown): PoiCategorySettings {
  const stored = value && typeof value === 'object' && !Array.isArray(value) ? (value as Record<string, unknown>) : {};
  return Object.fromEntries(POI_CATEGORIES.map(({ id }) => [id, typeof stored[id] === 'boolean' ? stored[id] : true]));
}

export function poiCategoryForKind(kind: string): PoiCategory | undefined {
  return POI_CATEGORIES.find((category) => category.kinds.includes(kind));
}
