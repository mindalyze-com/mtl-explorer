"""Resolve precompiled conda-forge media packages for both release platforms."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile


DIRECTORY = Path(__file__).resolve().parent
PLATFORMS = ("linux-64", "linux-aarch64")
CHANNEL_URL = "https://conda.anaconda.org/conda-forge/"


def render_lock(platform: str, solution: dict, specification: bytes) -> str:
    if not solution.get("success") or not solution.get("actions", {}).get("LINK"):
        raise ValueError(f"No successful package solution for {platform}")
    lines = [
        "# Generated by update-locks.py; do not edit individual packages.",
        f"# platform: {platform}",
        f"# media-specs-sha256: {hashlib.sha256(specification).hexdigest()}",
        "# Package URL fragments are SHA-256 checksums.",
        "@EXPLICIT",
    ]
    # Explicit installs preserve this order. Keep dependencies before packages
    # whose post-link scripts need their libraries and plugin tools.
    for package in solution["actions"]["LINK"]:
        url, checksum = package["url"], package.get("sha256", "")
        if not url.startswith(CHANNEL_URL) or package["subdir"] not in (platform, "noarch"):
            raise ValueError(f"Unexpected package source: {url}")
        if not re.fullmatch(r"[a-f0-9]{64}", checksum):
            raise ValueError(f"Missing SHA-256 for {url}")
        lines.append(f"{url}#{checksum}")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--micromamba", default="micromamba")
    args = parser.parse_args()
    specification = (DIRECTORY / "media-specs.txt").read_bytes()
    locks = {}
    with tempfile.TemporaryDirectory(prefix="mtl-media-solve-") as directory:
        for platform in PLATFORMS:
            print(f"Resolving conda-forge packages for {platform}", flush=True)
            command = [
                args.micromamba, "create", "--no-rc", "--root-prefix", directory,
                "--prefix", f"{directory}/environment", "--platform", platform,
                "--override-channels", "-c", "conda-forge", "--strict-channel-priority",
                "--file", str(DIRECTORY / "media-specs.txt"), "--dry-run", "--json",
            ]
            result = subprocess.run(command, check=True, stdout=subprocess.PIPE, text=True)
            locks[platform] = render_lock(platform, json.loads(result.stdout), specification)
    # Write only after both platforms resolve successfully.
    for platform, content in locks.items():
        path = DIRECTORY / f"conda-{platform}.lock"
        path.write_text(content)
        print(f"Updated {path}", flush=True)


if __name__ == "__main__":
    main()
